export function createNewInspectionSession(): InspectionSession {
  const now = new Date();
  const dateStr = now.toISOString().split('T')[0];
  const timeStr = now.toTimeString().slice(0, 5);

  const savedInspector = typeof window !== 'undefined' ? localStorage.getItem('ehs_last_inspector') || '' : '';
  const savedRole = typeof window !== 'undefined' ? localStorage.getItem('ehs_last_role') || 'EHS Specialist / Shift Lead' : 'EHS Specialist / Shift Lead';
  const savedFacility = typeof window !== 'undefined' ? localStorage.getItem('ehs_last_facility') || 'Main Plant & Logistics Center' : 'Main Plant & Logistics Center';

  return {
    id: `INS-${dateStr.replace(/-/g, '')}-${Math.random().toString(36).substring(2, 7).toUpperCase()}`,
    date: dateStr,
    startTime: timeStr,
    endTime: '',
    facilityName: savedFacility,
    facilityArea: 'All Zones (Ceilings, Aisles, Docks, Grounds)',
    shift: 'Смена 1 (Дневная / Day Shift)',
    inspectorName: savedInspector || 'Иванов А. С.',
    inspectorRole: savedRole,
    items: CHECKLIST_ITEMS_TEMPLATE.map((item) => ({ ...item })),
    generalNotes: '',
    status: 'In Progress',
    signatures: {
      inspector: savedInspector || 'Иванов А. С.',
      inspectorTitle: savedRole,
      timestamp: new Date().toISOString(),
    },
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
  };
}
